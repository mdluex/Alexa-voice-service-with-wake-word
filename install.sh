#!/usr/bin/env bash
# One-command installer: real Amazon Alexa (AVS SampleApp) + wake word on Raspberry Pi.
#
# Recommended (clone then install):
#   git clone https://github.com/mdluex/Alexa-voice-service-with-wake-word.git
#   cd Alexa-voice-service-with-wake-word
#   ./install.sh
#
# One-liner (downloads this script, clones repo if needed, then installs):
#   curl -fsSL https://raw.githubusercontent.com/mdluex/Alexa-voice-service-with-wake-word/main/install.sh | bash
#
# Interactive only for Amazon requirements:
#   - AVS config.json / Client ID + Product ID
#   - Login with Amazon Code-Based Linking (browser)
#
# Environment knobs:
#   SKIP_AVS_BUILD=1     Skip compiling the AVS Device SDK
#   SKIP_AUTHORIZE=1     Skip interactive CBL authorization
#   SKIP_SERVICE=1       Skip enabling systemd
#   AVS_DIR=~/avs-sdk    SampleApp install directory
#   REPO_URL=...         Override git clone URL for curl|bash
set -euo pipefail

REPO_NAME="Alexa-voice-service-with-wake-word"
REPO_URL="${REPO_URL:-https://github.com/mdluex/Alexa-voice-service-with-wake-word.git}"
BRANCH="${BRANCH:-main}"

resolve_repo_root() {
  local script_path
  if [[ -n "${BASH_SOURCE[0]:-}" && -f "${BASH_SOURCE[0]}" ]]; then
    script_path="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
    if [[ -f "$script_path/pi_voice_assistant/__init__.py" ]]; then
      echo "$script_path"
      return
    fi
  fi

  # curl | bash: script may be stdin; clone into $HOME if needed.
  local target="${INSTALL_DIR:-$HOME/$REPO_NAME}"
  if [[ ! -d "$target/.git" ]]; then
    echo "==> Cloning $REPO_URL into $target"
    git clone --branch "$BRANCH" "$REPO_URL" "$target"
  else
    echo "==> Using existing clone at $target"
    git -C "$target" fetch origin "$BRANCH" || true
    git -C "$target" checkout "$BRANCH" || true
    git -C "$target" pull --ff-only origin "$BRANCH" || true
  fi
  echo "$target"
}

# Always prompt on the terminal. Required for `curl ... | bash` where stdin is the script.
prompt() {
  local message="$1"
  local default="${2:-}"
  local reply
  if [[ -n "$default" ]]; then
    read -r -p "$message [$default]: " reply </dev/tty
    echo "${reply:-$default}"
  else
    read -r -p "$message: " reply </dev/tty
    echo "$reply"
  fi
}

prompt_secret() {
  local message="$1"
  local reply
  read -r -s -p "$message: " reply </dev/tty
  echo >/dev/tty
  echo "$reply"
}

ensure_avs_config_json() {
  local avs_dir="$1"
  local dest="$avs_dir/config.json"
  mkdir -p "$avs_dir"

  if [[ -n "${AVS_CONFIG_JSON:-}" && -f "${AVS_CONFIG_JSON}" ]]; then
    cp "${AVS_CONFIG_JSON}" "$dest"
    chmod 600 "$dest"
    echo "==> Using AVS_CONFIG_JSON=$AVS_CONFIG_JSON"
    return
  fi

  if [[ -f "$dest" ]]; then
    echo "==> Found existing $dest"
    return
  fi

  echo
  echo "Amazon AVS credentials are required (config.json from the developer console)."
  echo "See docs/AMAZON_AVS.md — new AVS registrations may be blocked by Amazon."
  echo
  local existing
  existing="$(prompt "Path to existing config.json (or leave blank to paste Client ID / Product ID)" "")"
  if [[ -n "$existing" ]]; then
    if [[ ! -f "$existing" ]]; then
      echo "File not found: $existing" >&2
      exit 1
    fi
    cp "$existing" "$dest"
    chmod 600 "$dest"
    return
  fi

  local client_id product_id
  client_id="$(prompt_secret "Paste Amazon Client ID")"
  product_id="$(prompt "Paste Amazon Product ID")"
  if [[ -z "$client_id" || -z "$product_id" ]]; then
    echo "Client ID and Product ID are required." >&2
    exit 1
  fi
  python3 - "$dest" "$client_id" "$product_id" <<'PY'
import json, sys
path, client_id, product_id = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path, "w", encoding="utf-8") as fh:
    json.dump({"clientId": client_id, "productId": product_id}, fh, indent=2)
    fh.write("\n")
PY
  chmod 600 "$dest"
  echo "==> Wrote $dest (permissions 600)"
}

write_config_env() {
  local config_path="$1"
  local avs_start="$2"
  local install_user="$3"
  cat >"$config_path" <<EOF
# Generated by install.sh — do not commit secrets.
WAKE_ENGINE=openwakeword
WAKE_MODEL=alexa
WAKE_THRESHOLD=0.5
WAKE_COOLDOWN_SECONDS=2.0
SAMPLE_RATE=16000
BACKEND=avs
AVS_START_SCRIPT=$avs_start
PLAY_STARTUP_SOUND=true
EOF
  chown "$install_user":"$install_user" "$config_path" 2>/dev/null || true
  chmod 600 "$config_path"
}

main() {
  if [[ "$(id -u)" -eq 0 && -z "${SUDO_USER:-}" ]]; then
    echo "Run as a normal user with sudo privileges (not as root login)." >&2
    exit 1
  fi

  echo "=============================================="
  echo " Pi Alexa installer (real Amazon AVS SampleApp)"
  echo "=============================================="

  # Ensure git exists before possible clone.
  if ! command -v git >/dev/null 2>&1; then
    sudo apt-get update
    sudo apt-get install -y git curl ca-certificates
  fi

  REPO_ROOT="$(resolve_repo_root)"
  cd "$REPO_ROOT"
  chmod +x scripts/*.sh install.sh 2>/dev/null || true

  INSTALL_USER="${SUDO_USER:-${USER}}"
  HOME_DIR="$(getent passwd "$INSTALL_USER" | cut -d: -f6)"
  VENV_DIR="${VENV_DIR:-$HOME_DIR/.venvs/pi-voice-assistant}"
  CONFIG_DIR="${CONFIG_DIR:-/etc/pi-voice-assistant}"
  AVS_DIR="${AVS_DIR:-$HOME_DIR/avs-sdk}"

  echo "==> Repo: $REPO_ROOT"
  echo "==> User: $INSTALL_USER"
  echo "==> AVS:  $AVS_DIR"

  # 1) Python wake-word daemon deps
  "$REPO_ROOT/scripts/install.sh"

  # 2) Amazon credentials (interactive if missing)
  ensure_avs_config_json "$AVS_DIR"

  # 3) Build archived AVS Device SDK SampleApp
  if [[ "${SKIP_AVS_BUILD:-0}" != "1" ]]; then
    "$REPO_ROOT/scripts/install-avs-sdk.sh" "$AVS_DIR/config.json"
  else
    echo "==> SKIP_AVS_BUILD=1 — not compiling SampleApp"
  fi

  AVS_START="${AVS_DIR}/startsample.sh"
  sudo mkdir -p "$CONFIG_DIR"
  write_config_env "$CONFIG_DIR/config.env" "$AVS_START" "$INSTALL_USER"
  write_config_env "$REPO_ROOT/config.env" "$AVS_START" "$INSTALL_USER"

  # 4) Login with Amazon authorization (must be interactive)
  if [[ "${SKIP_AUTHORIZE:-0}" != "1" ]]; then
    if [[ -x "$AVS_START" ]]; then
      echo
      echo "Next: Amazon Code-Based Linking (required once)."
      echo "A browser step at https://amazon.com/us/code is required by Amazon."
      local go
      go="$(prompt "Start authorization now? (Y/n)" "Y")"
      if [[ "${go,,}" != "n" && "${go,,}" != "no" ]]; then
        "$REPO_ROOT/scripts/authorize-avs.sh" || {
          echo "Authorization exited non-zero. Re-run: $REPO_ROOT/scripts/authorize-avs.sh" >&2
        }
      else
        echo "Skipped. Run later: $REPO_ROOT/scripts/authorize-avs.sh"
      fi
    else
      echo "WARNING: $AVS_START missing — authorize after a successful AVS build."
    fi
  else
    echo "==> SKIP_AUTHORIZE=1"
  fi

  # 5) systemd start-on-boot
  if [[ "${SKIP_SERVICE:-0}" != "1" ]]; then
    if [[ -x "$AVS_START" ]]; then
      "$REPO_ROOT/scripts/install-service.sh"
    else
      echo "WARNING: SampleApp missing; not enabling systemd yet."
      echo "After a successful build + authorize, run: $REPO_ROOT/scripts/install-service.sh"
    fi
  else
    echo "==> SKIP_SERVICE=1"
  fi

  cat <<EOF

==============================================
 Install finished
==============================================
 Config:     $CONFIG_DIR/config.env
 SampleApp:  $AVS_START
 Service:    pi-voice-assistant.service

 Useful:
   sudo systemctl status pi-voice-assistant
   sudo journalctl -u pi-voice-assistant -f
   $REPO_ROOT/scripts/authorize-avs.sh

 Amazon availability note:
   AVS developer tools are no longer generally available for new Alexa Built-in
   products. Details: $REPO_ROOT/docs/AMAZON_AVS.md
==============================================
EOF
}

main "$@"
